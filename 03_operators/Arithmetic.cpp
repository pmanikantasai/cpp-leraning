#include <iostream>

using namespace std;

int main (){
    // here arithmetic operators are +, -, *, %, / 
    int a, b;
    a=20;
    b=5;
    // by using +
    cout << a+b << endl;
    // by using -
    cout << a-b << endl;
    // by using *
    cout << a*b << endl;
    // by using %
    cout << a % b << endl;
    // by using /
    cout << a / b << endl; 


    return 0;
}