#include <iostream>

using namespace std;

int main (){
    // ==, !=, <, > , >=, <=

    int a,b,c;
    a=20;
    b=20;
    c=10;

    cout << (a == b) << endl;
    cout << (a != b) << endl;
    cout << (a != c)<< endl;
    cout <<(a < c)<< endl;
    cout <<(a > c)<< endl;
    cout <<(a <= c)<< endl;
    cout <<(a >= c)<< endl;

    // here we bool values 1(true),0(false)

    return 0;
}